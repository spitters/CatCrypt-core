#!/usr/bin/env bash
# Deletion gate: a commit that removes a Lean declaration says where it went.
#
#   bash scripts/deletion-gate.sh staged
#
# Compares the staged tree with HEAD. A declaration is removed when its fully
# qualified name (namespace stack + written name, `_root_.` honoured) is declared
# in the HEAD version of a changed .lean file and no longer in the staged version
# of that file. Kinds: theorem, lemma, def, abbrev, structure, inductive, class
# (also `class inductive`, `class abbrev`) and named instance. A deleted or renamed
# file counts as removing every declaration of its HEAD version.
#
# Each removed name is resolved in one of two ways:
#   (a) a move: a declaration of the same fully qualified name exists after the
#       commit somewhere in the workspace, that is, in the staged tree of this
#       repository or in the working tree of a sibling repository (the list of
#       siblings is SIBLINGS below). A hit in
#       a sibling at the same relative path as the file it was removed from is a
#       republished copy of that file and does not count.
#   (b) a row of the staged ledger `scripts/deletion-ledger.tsv`, columns
#         name  removed_in  successor  decision  note
#       where `name` is the fully qualified name (or the name as written), and at
#       least one of `successor` (a declaration name) and `decision` (a path
#       under `docs/` or `coord/` of the decisions repository, given by
#       $DELETION_DECISIONS_DIR or `git config deletion-gate.decisions`) is set, the other `-`. A set
#       successor must be declared after the commit (as in (a)); a set decision
#       must be an existing file.
# A ledger row, old or new, whose successor this commit removes without moving it
# is refused: the row is updated in the same commit. Rows added to the ledger by
# the commit are checked in full. There is no override token; the ledger is the
# override.
#
# Exempt (not tracked as removals):
#   - `private` declarations, `example`s, anonymous instances (no written name);
#   - test and scratch files: a directory component Test, Tests, test, tests,
#     Scratch or _mcp_scratch, or a file stem ending in Test, Tests, TestVectors or
#     Scratch, or starting with Scratch or _mcp_scratch;
#   - generated files: *_haxpipe.lean (regenerated by scripts/reextract.sh); the
#     generated module lists (umbrella CatCrypt.lean, lakefile globs) hold imports
#     only and no declarations;
#   - declarations whose name is on a line after the keyword line (not parsed).
#
# Speed: a commit that deletes, renames or modifies no .lean file and does not
# touch the ledger exits at once; a modified file is parsed only when a removed
# line is a declaration or structure line (namespace/section/end/mutual), or an
# added line opens or closes a block comment or a namespace.
#
# Environment (tests): DELETION_GATE_ROOTS (space-separated sibling directories
# searched in their working trees; default: the sibling list below, under the
# parent of this repository), DELETION_DECISIONS_DIR (the decisions repository;
# default `git config deletion-gate.decisions`).
#
# Exit: 0 every removal resolved, 1 some name unresolved or a ledger row invalid,
# 2 usage.
set -uo pipefail

if [ "${1:-}" != "staged" ]; then
  sed -n '2,4p' "$0" | sed 's/^# \{0,1\}//' >&2
  exit 2
fi
top="$(git rev-parse --show-toplevel 2>/dev/null)" || exit 2
cd "$top" || exit 2
git rev-parse --verify -q HEAD >/dev/null || exit 0   # first commit: nothing removed

lean_changed="$(git diff --cached --name-only --diff-filter=DMR -- '*.lean' 2>/dev/null)"
ledger_changed="$(git diff --cached --name-only -- scripts/deletion-ledger.tsv 2>/dev/null)"
[ -z "$lean_changed" ] && [ -z "$ledger_changed" ] && exit 0

exec python3 - "$top" <<'PY'
import os, re, subprocess, sys, tempfile

TOP = sys.argv[1]
os.chdir(TOP)
LEDGER = "scripts/deletion-ledger.tsv"
def _decisions_dir():
    d = os.environ.get("DELETION_DECISIONS_DIR")
    if d:
        return d
    r = subprocess.run(["git", "config", "--get", "deletion-gate.decisions"],
                       capture_output=True, text=True)
    return os.path.expanduser(r.stdout.strip()) if r.returncode == 0 else ""
PRIV = _decisions_dir()
SIBLINGS = ["SSProve-lean", "CatCrypt-core", "ParamTransfer", "hax-lean", "veir", "nominal-lean",
            "catcrypt-easycrypt", "catcrypt-compiler", "catcrypt-vcvio", "catcrypt-arklib"]

def git(*args, inp=None):
    r = subprocess.run(["git", "-c", "core.quotePath=false", *args], input=inp,
                       capture_output=True)
    return r.returncode, r.stdout

# ---------------------------------------------------------------- Lean parsing
MODS = r"(?:private|protected|noncomputable|partial|unsafe|nonrec|scoped|local|public|meta)"
ATTR = r"@\[(?:[^\[\]]|\[[^\]]*\])*\]"
KW = r"(theorem|lemma|def|abbrev|structure|inductive|class(?:\s+(?:inductive|abbrev))?|instance)"
DECL_RE = re.compile(r"^\s*(?:" + ATTR + r"\s*)*((?:" + MODS + r"\s+(?:" + ATTR + r"\s*)*)*)"
                     + KW + r"(?=\s|$)\s*(.*)$")
NAME_RE = re.compile(r"[^\s:(){}\[\]⦃⦄,]+")
PRIO_RE = re.compile(r"^\(priority\s*:=[^)]*\)\s*")
NS_RE = re.compile(r"^\s*namespace\s+(\S+)")
SEC_RE = re.compile(r"^\s*(?:(?:noncomputable|public|private|" + ATTR + r")\s+)*section\b")
MUT_RE = re.compile(r"^\s*mutual\b")
END_RE = re.compile(r"^\s*end\b")
BLK = re.compile(r"/-|-/")
STR = re.compile(r'\\.|"')
NORM = re.compile(r"""/-|--|"|'(?:\\[^']*|[^\\'])'""")

def code_lines(text):
    """Each line with comments and string contents removed."""
    depth, in_str, out = 0, False, []
    for line in text.split("\n"):
        buf, i, n = [], 0, len(line)
        while i < n:
            if depth:
                m = BLK.search(line, i)
                if not m:
                    break
                depth += 1 if m.group() == "/-" else -1
                i = m.end()
                continue
            if in_str:
                m = STR.search(line, i)
                if not m:
                    break
                i = m.end()
                if m.group() == '"':
                    in_str = False
                    buf.append('""')
                continue
            m = NORM.search(line, i)
            if not m:
                buf.append(line[i:])
                break
            buf.append(line[i:m.start()])
            t = m.group()
            if t == "--":
                break
            if t == "/-":
                depth = 1
            elif t == '"':
                in_str = True
            else:
                buf.append(" ")
            i = m.end()
        out.append("".join(buf))
    return out

def decl_name(kw, rest):
    if kw == "instance":
        rest = PRIO_RE.sub("", rest)
    m = NAME_RE.match(rest)
    if not m:
        return None
    name = m.group().rstrip(".")
    return name or None

def last_comp(name):
    return name.rsplit(".", 1)[-1]

def decls(text):
    """[(fq, written, line, private)] for the declarations of a Lean source."""
    res, stack = [], []
    for ln, code in enumerate(code_lines(text), 1):
        if not code.strip():
            continue
        m = DECL_RE.match(code)
        if m:
            kw = m.group(2).split()[0]
            w = decl_name(kw, m.group(3))
            if w:
                if w.startswith("_root_."):
                    fq = w[len("_root_."):]
                else:
                    ns = [p for kind, parts in stack if kind == "ns" for p in parts]
                    fq = ".".join(ns + [w])
                res.append((fq, w, ln, "private" in m.group(1).split()))
            continue
        m = NS_RE.match(code)
        if m:
            stack.append(("ns", m.group(1).split(".")))
        elif SEC_RE.match(code):
            stack.append(("sec", []))
        elif MUT_RE.match(code):
            stack.append(("mut", []))
        elif END_RE.match(code) and stack:
            stack.pop()
    return res

# ---------------------------------------------------------------- exemptions
EXEMPT_DIRS = {"Test", "Tests", "test", "tests", "Scratch", "_mcp_scratch"}
def exempt(path):
    parts = path.split("/")
    if any(p in EXEMPT_DIRS for p in parts[:-1]):
        return True
    stem = parts[-1][:-5] if parts[-1].endswith(".lean") else parts[-1]
    if stem.endswith("_haxpipe"):
        return True
    if re.search(r"(Test|Tests|TestVectors|Scratch)$", stem) or re.match(r"(Scratch|_mcp_scratch)", stem):
        return True
    return False

# ---------------------------------------------------------------- git objects
def cat_batch(specs):
    """{spec: text or None} via one `git cat-file --batch`."""
    if not specs:
        return {}
    rc, out = git("cat-file", "--batch", inp="".join(s + "\n" for s in specs).encode())
    res, pos = {}, 0
    for s in specs:
        nl = out.index(b"\n", pos)
        hdr = out[pos:nl].decode(errors="replace")
        pos = nl + 1
        if hdr.endswith(" missing") or hdr.endswith(" ambiguous"):
            res[s] = None
            continue
        size = int(hdr.rsplit(" ", 1)[1])
        res[s] = out[pos:pos + size].decode("utf-8", errors="replace")
        pos += size + 1
    return res

# ---------------------------------------------------------------- staged changes
rc, raw = git("diff", "--cached", "--name-status", "-M", "-z", "--", "*.lean")
toks = raw.decode("utf-8", errors="replace").split("\0")
entries = []          # (old, new) ; new None for a deletion
i = 0
while i < len(toks) and toks[i]:
    st = toks[i]
    if st[0] in "RC":
        old, new = toks[i + 1], toks[i + 2]
        i += 3
        if st[0] == "R":
            entries.append((old, new))
        continue
    p = toks[i + 1]
    i += 2
    if st[0] == "D":
        entries.append((p, None))
    elif st[0] in "MT":
        entries.append((p, p))

# Which modified or renamed files need a parse: a removed declaration or structure
# line, or an added structure or block-comment line.
TRIG_RM = re.compile(r"^\s*(?:" + ATTR + r"\s*)*(?:" + MODS + r"\s+)*(?:" + KW
                     + r"|namespace|section|end|mutual)(?=\s|$)|/-|-/")
TRIG_ADD = re.compile(r"^\s*(?:namespace|end|mutual)(?=\s|$)|^\s*(?:\S+\s+)*section(?=\s|$)")
need = set()
mod_paths = [o for o, n in entries if n is not None and not exempt(o)]
if mod_paths:
    rc, diff = git("diff", "--cached", "-U0", "-M", "--no-color", "--no-ext-diff", "--", "*.lean")
    cur, in_hdr = None, False
    for line in diff.decode("utf-8", errors="replace").split("\n"):
        if line.startswith("diff --git "):
            in_hdr, cur = True, None
            continue
        if in_hdr:
            if line.startswith("--- a/"):
                cur = line[6:]
            elif line.startswith("@@"):
                in_hdr = False
            continue
        if cur is None or cur in need:
            continue
        if line.startswith("-") and TRIG_RM.search(line[1:]):
            need.add(cur)
        elif line.startswith("+"):
            body = line[1:]
            if TRIG_ADD.search(body) or (("/-" in body) != ("-/" in body)):
                need.add(cur)

work = [(o, n) for o, n in entries if not exempt(o) and (n is None or o in need)]
specs = []
for o, n in work:
    specs.append("HEAD:" + o)
    if n is not None:
        specs.append(":" + n)
blobs = cat_batch(specs)

removed = {}          # fq -> (path, line, written)
for o, n in work:
    old = blobs.get("HEAD:" + o)
    if old is None:
        continue
    new_fqs = set()
    if n is not None and blobs.get(":" + n) is not None:
        new_fqs = {d[0] for d in decls(blobs[":" + n])}
    for fq, w, ln, priv in decls(old):
        if not priv and fq not in new_fqs and fq not in removed:
            removed[fq] = (o, ln, w)

# ---------------------------------------------------------------- ledger
def ledger_rows(text):
    rows = []
    for ln, line in enumerate((text or "").split("\n"), 1):
        if not line.strip() or line.startswith("#"):
            continue
        cols = line.split("\t")
        if cols[0] == "name":
            continue
        cols += [""] * (5 - len(cols))
        rows.append({"name": cols[0].strip(), "removed_in": cols[1].strip(),
                     "successor": cols[2].strip(), "decision": cols[3].strip(),
                     "line": ln, "raw": line})
    return rows

lb = cat_batch([":" + LEDGER, "HEAD:" + LEDGER])
rows = ledger_rows(lb[":" + LEDGER])
head_raw = {r["raw"] for r in ledger_rows(lb["HEAD:" + LEDGER])}
added_rows = [r for r in rows if r["raw"] not in head_raw]

if not removed and not added_rows:
    sys.exit(0)

def unset(v):
    return v in ("", "-")

written = {fq: v[2] for fq, v in removed.items()}
by_name = {}
for r in rows:
    by_name.setdefault(r["name"], []).append(r)
def rows_for(fq):
    out = list(by_name.get(fq, []))
    w = written.get(fq)
    if w and w != fq:
        out += by_name.get(w, [])
    return out

check_rows = set()
for fq in removed:
    for r in rows_for(fq):
        check_rows.add(r["line"])
for r in rows:
    if r["successor"] in removed or r["line"] in {a["line"] for a in added_rows}:
        check_rows.add(r["line"])
crow = [r for r in rows if r["line"] in check_rows]

# ---------------------------------------------------------------- workspace search
want = {last_comp(fq) for fq in removed}
want |= {last_comp(r["successor"]) for r in crow if not unset(r["successor"])}
want.discard("")

roots_env = os.environ.get("DELETION_GATE_ROOTS")
if roots_env is not None:
    roots = [r for r in roots_env.split() if r]
else:
    base = os.path.dirname(TOP)
    roots = [os.path.join(base, d) for d in SIBLINGS]
top_real = os.path.realpath(TOP)
roots = [r for r in roots if os.path.isdir(r) and os.path.realpath(r) != top_real]

found = {}            # fq -> [(root or None, relpath)]
def note(root, rel, text):
    for fq, w, ln, priv in decls(text):
        if not priv and last_comp(fq) in want:
            found.setdefault(fq, []).append((root, rel))

def cand(content):
    m = DECL_RE.match(content)
    if not m:
        return False
    w = decl_name(m.group(2).split()[0], m.group(3))
    return bool(w) and last_comp(w) in want

if want:
    with tempfile.NamedTemporaryFile("w", suffix=".pat", delete=False) as pf:
        pf.write("\n".join(sorted(want)) + "\n")
        patfile = pf.name
    try:
        rc, out = git("grep", "--cached", "-n", "-I", "-F", "-f", patfile, "--", "*.lean")
        files = set()
        for line in out.decode("utf-8", errors="replace").split("\n"):
            parts = line.split(":", 2)
            if len(parts) == 3 and parts[0] not in files and cand(parts[2]):
                files.add(parts[0])
        texts = cat_batch([":" + f for f in sorted(files)])
        for f in sorted(files):
            if texts.get(":" + f) is not None:
                note(None, f, texts[":" + f])
        if roots:
            if subprocess.run(["sh", "-c", "command -v rg"], capture_output=True).returncode == 0:
                cmd = ["rg", "--no-heading", "-n", "--color=never", "-F", "-f", patfile,
                       "-g", "*.lean", "-g", "!.lake", "-g", "!**/.lake/**", "-g", "!build/**", *roots]
            else:
                cmd = ["grep", "-rIn", "--include=*.lean", "--exclude-dir=.lake",
                       "--exclude-dir=build", "-F", "-f", patfile, *roots]
            out = subprocess.run(cmd, capture_output=True).stdout.decode("utf-8", errors="replace")
            files = set()
            for line in out.split("\n"):
                parts = line.split(":", 2)
                if len(parts) == 3 and parts[0] not in files and cand(parts[2]):
                    files.add(parts[0])
            for f in sorted(files):
                root = next((r for r in roots if f.startswith(r.rstrip("/") + "/")), None)
                rel = f[len(root.rstrip("/")) + 1:] if root else f
                try:
                    with open(f, encoding="utf-8", errors="replace") as fh:
                        note(root, rel, fh.read())
                except OSError:
                    pass
    finally:
        os.unlink(patfile)

def exists(fq, from_path=None):
    for root, rel in found.get(fq, []):
        if root is not None and from_path is not None and rel == from_path:
            continue      # a republished copy of the file it was removed from
        return True
    return False

# ---------------------------------------------------------------- verdict
problems = []
def row_errors(r):
    errs = []
    s, d = r["successor"], r["decision"]
    if unset(s) and unset(d):
        errs.append("names neither a successor nor a decision")
    if not unset(s) and not exists(s):
        why = "which this commit removes" if s in removed else "which is declared nowhere after this commit"
        errs.append("successor %s, %s" % (s, why))
    if not unset(d):
        ok = re.match(r"^(docs|coord)/", d) and ".." not in d.split("/")
        if not ok:
            errs.append("decision %s is not a path under docs/ or coord/ of the decisions repository" % d)
        elif not os.path.isfile(os.path.join(PRIV, d)):
            errs.append("decision file %s does not exist in %s" % (d, PRIV))
    return errs

reported = set()
for fq in sorted(removed):
    path, ln, w = removed[fq]
    if exists(fq, path):
        continue
    rs = rows_for(fq)
    if not rs:
        problems.append("UNRESOLVED %s (%s:%d): declare it elsewhere in the workspace (a move), "
                        "or add a row to %s naming a successor declaration or a decision file "
                        "under docs/ or coord/ of the decisions repository" % (fq, path, ln, LEDGER))
        continue
    if not any(not row_errors(r) for r in rs):
        for r in rs:
            reported.add(r["line"])
            problems.append("LEDGER %s (%s:%d, ledger line %d): %s" %
                            (fq, path, ln, r["line"], "; ".join(row_errors(r))))
for r in crow:
    if r["line"] in reported:
        continue
    errs = row_errors(r)
    if errs:
        problems.append("LEDGER row %s (ledger line %d): %s; update the row in this commit" %
                        (r["name"], r["line"], "; ".join(errs)))

if problems:
    print("deletion-gate: declarations removed without a successor or decision:", file=sys.stderr)
    for p in problems:
        print("  " + p, file=sys.stderr)
    print("Ledger %s (staged), tab-separated: name, removed_in, successor, decision, note;\n"
          "successor or decision is set, the other '-'." % LEDGER, file=sys.stderr)
    sys.exit(1)
sys.exit(0)
